// Emits the same content prisma/seed.ts inserts, as plain SQL. Useful when you
// can apply migrations through the Supabase dashboard or MCP but do not have
// the database password on hand for a direct Prisma connection.

import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { legacyRooms } from '../prisma/seed-data/legacy-rooms.ts';

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '../prisma/manual/seed_content.sql');

const ROOM_TYPES = { Walkthrough: 'WALKTHROUGH', Challenge: 'CHALLENGE', Analysis: 'ANALYSIS' };
const DIFFICULTIES = { 'Başlanğıc': 'BEGINNER', Orta: 'INTERMEDIATE', 'Çətin': 'ADVANCED' };
const TRANSLITERATION = { ə: 'e', ı: 'i', ö: 'o', ü: 'u', ğ: 'g', ş: 's', ç: 'c', İ: 'i' };

function slugify(value) {
  return value
    .toLocaleLowerCase('az')
    .replace(/[əıöüğşçİ]/g, (char) => TRANSLITERATION[char] ?? char)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function distributePoints(total, count) {
  if (count === 0) return [];
  const base = Math.floor(total / count);
  const shares = Array.from({ length: count }, () => base);
  for (let i = 0; i < total - base * count; i += 1) shares[i] += 1;
  return shares;
}

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const arr = (values) => `array[${values.map(q).join(', ')}]::text[]`;
const json = (value) => `${q(JSON.stringify(value))}::jsonb`;

const lines = [
  '-- Generated by scripts/generate-seed-sql.mjs. Idempotent: safe to re-run.',
  'begin;',
  '',
  "insert into public.organizations (slug, name) values ('baki-texniki-kolleci', 'Bakı Texniki Kolleci')",
  '  on conflict (slug) do nothing;',
  '',
  'insert into public.class_groups (organization_id, name, academic_year)',
  "select id, '11A', '2026/2027' from public.organizations where slug = 'baki-texniki-kolleci'",
  '  on conflict (organization_id, name) do nothing;',
  '',
];

legacyRooms.forEach((room, roomIndex) => {
  const pathSlug = slugify(room.path);
  const moduleSlug = slugify(room.module);
  const shares = distributePoints(room.points, room.tasks.length);

  lines.push(`-- ${room.title}`);
  lines.push(
    'insert into public.paths (slug, title, description, category, status, order_index) values',
    `  (${q(pathSlug)}, ${q(room.path)}, ${q(`${room.path} kurikulumu`)}, ${q(room.category)}, 'PUBLISHED', ${roomIndex})`,
    "  on conflict (slug) do update set status = 'PUBLISHED';",
    '',
    'insert into public.learning_modules (path_id, slug, title, status, order_index)',
    `select id, ${q(moduleSlug)}, ${q(room.module)}, 'PUBLISHED', 0 from public.paths where slug = ${q(pathSlug)}`,
    "  on conflict (path_id, slug) do update set status = 'PUBLISHED';",
    '',
    'insert into public.rooms (',
    '  module_id, slug, title, short_title, eyebrow, description, category, type, difficulty,',
    '  duration_label, points, accent, objectives, source_file, status, order_index, published_at',
    ')',
    'select m.id,',
    `  ${q(room.slug)}, ${q(room.title)}, ${q(room.shortTitle)}, ${q(room.eyebrow)}, ${q(room.description)},`,
    `  ${q(room.category)}, ${q(ROOM_TYPES[room.type])}::public.room_type, ${q(DIFFICULTIES[room.difficulty])}::public.difficulty,`,
    `  ${q(room.duration)}, ${room.points}, ${q(room.accent === 'green' ? 'GREEN' : 'RED')}::public.content_accent,`,
    `  ${arr(room.objectives)}, ${q(room.sourceFile)}, 'PUBLISHED', ${roomIndex}, now()`,
    'from public.learning_modules m',
    `join public.paths p on p.id = m.path_id and p.slug = ${q(pathSlug)}`,
    `where m.slug = ${q(moduleSlug)}`,
    '  on conflict (slug) do update set',
    '    title = excluded.title, description = excluded.description, objectives = excluded.objectives,',
    "    points = excluded.points, status = 'PUBLISHED';",
    '',
    `delete from public.tasks where room_id = (select id from public.rooms where slug = ${q(room.slug)});`,
    '',
  );

  room.tasks.forEach((task, taskIndex) => {
    const points = shares[taskIndex] ?? 0;

    lines.push(
      'with new_task as (',
      '  insert into public.tasks (room_id, order_index, title, duration_label, points, sections)',
      `  select id, ${task.id}, ${q(task.title)}, ${q(task.duration)}, ${points}, ${json(task.sections)}`,
      `  from public.rooms where slug = ${q(room.slug)}`,
      '  returning id',
      '), new_question as (',
      '  insert into public.questions (task_id, order_index, type, prompt, explanation, points)',
      `  select id, 1, 'SINGLE_CHOICE', ${q(task.question.prompt)}, ${q(task.question.explanation)}, ${points}`,
      '  from new_task',
      '  returning id',
      ')',
      'insert into public.question_options (question_id, order_index, label, is_correct)',
      'select new_question.id, opt.order_index, opt.label, opt.is_correct',
      'from new_question, (values',
      task.question.options
        .map((label, index) => `  (${index}, ${q(label)}, ${index === task.question.correctAnswer})`)
        .join(',\n'),
      ') as opt(order_index, label, is_correct);',
      '',
    );
  });
});

lines.push('commit;', '');

await writeFile(target, lines.join('\n'), 'utf8');

console.log(`Wrote ${target}`);
